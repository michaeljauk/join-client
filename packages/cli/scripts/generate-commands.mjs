#!/usr/bin/env node
// Reads openapi.json and emits one TypeScript file per resource under
// packages/cli/src/commands/generated/, plus a root barrel. Naming rules
// live in endpoints.mjs.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { endpoints, toCamel, toKebab } from "./endpoints.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(__dirname, "..", "src", "commands", "generated");

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const resources = new Map();
for (const ep of endpoints()) {
  if (!resources.has(ep.resource)) resources.set(ep.resource, []);
  resources.get(ep.resource).push(ep);
}

const exported = [];
for (const [resource, eps] of [...resources.entries()].toSorted(([a], [b]) =>
  a.localeCompare(b),
)) {
  const dupes = eps
    .map((e) => e.command)
    .filter((c, i, a) => a.indexOf(c) !== i);
  if (dupes.length)
    throw new Error(`duplicate commands in ${resource}: ${dupes.join(", ")}`);
  writeFileSync(
    join(outDir, `${resource}.ts`),
    emitResourceFile(resource, eps),
    "utf8",
  );
  exported.push({
    name: `${toCamel(resource)}Command`,
    file: `./${resource}.js`,
    resource,
  });
}

writeFileSync(
  join(outDir, "_root.ts"),
  "// AUTO-GENERATED by scripts/generate-commands.mjs - DO NOT EDIT\n" +
    `import type { CommandDef } from "citty";\n` +
    exported.map((e) => `import { ${e.name} } from "${e.file}";`).join("\n") +
    `\n\nexport const generatedSubCommands: Record<string, CommandDef> = {\n` +
    exported.map((e) => `  "${e.resource}": ${e.name},`).join("\n") +
    "\n};\n",
  "utf8",
);

const total = [...resources.values()].reduce((n, eps) => n + eps.length, 0);
console.log(
  `generated ${exported.length} resource command files (${total} endpoints)`,
);

function varName(cmd) {
  return "cmd_" + cmd.replace(/-/g, "_");
}

function emitResourceFile(resource, unsorted) {
  const eps = unsorted.toSorted((a, b) => a.command.localeCompare(b.command));
  const helpers = new Set(["globalArgs", "resolveClient"]);
  const body = eps
    .map((ep) => emitCommand(ep, varName(ep.command), helpers))
    .join("\n\n");
  return (
    `// AUTO-GENERATED by scripts/generate-commands.mjs - DO NOT EDIT\n` +
    `import { defineCommand } from "citty";\n` +
    `import type { JoinClient } from "join-sdk";\n` +
    `import { ${[...helpers].toSorted().join(", ")} } from "../_shared.js";\n\n` +
    body +
    `\n\nexport const ${toCamel(resource)}Command = defineCommand({\n` +
    `  meta: { name: "${resource}", description: "Manage ${resource}" },\n` +
    `  subCommands: {\n` +
    eps.map((ep) => `    "${ep.command}": ${varName(ep.command)},`).join("\n") +
    `\n  },\n});\n`
  );
}

function emitCommand(ep, constName, helpers) {
  const args = [`    ...globalArgs,`];
  for (const p of ep.positionals) {
    args.push(
      `    "${toKebab(p.name)}": { type: "positional", description: ${str(p.description)}, required: true },`,
    );
  }
  const queryFlags = [];
  for (const q of ep.query) {
    const flag = toKebab(q.name);
    const type = q.schema?.type === "boolean" ? "boolean" : "string";
    const req = q.required ? ", required: true" : "";
    args.push(
      `    "${flag}": { type: "${type}", description: ${str(q.description ?? q.name)}${req} },`,
    );
    queryFlags.push({ raw: q.name, flag, schema: q.schema ?? {} });
  }
  const headerFlags = [];
  for (const h of ep.header) {
    const flag = toKebab(h.name);
    args.push(
      `    "${flag}": { type: "string", description: ${str(h.description ?? h.name)} },`,
    );
    headerFlags.push({ raw: h.name, flag });
  }
  if (ep.paginated) {
    args.push(
      `    all: { type: "boolean", description: "Follow nextCursor from --cursor (default: the start) and print all records as one array" },`,
    );
  }
  if (ep.hasBody) {
    args.push(
      `    data: { type: "string", description: "Request body as JSON string, @file.json, or '-' for stdin" },`,
    );
    helpers.add("readBody");
  }
  if (ep.binary) {
    const fileParam = ep.positionals.at(-1)?.name;
    const fallback = fileParam
      ? ` (default: the ${toKebab(fileParam)} argument)`
      : "";
    args.push(
      `    output: { type: "string", alias: "o", description: "Output file, or '-' for stdout${fallback}" },`,
    );
  }

  const parts = [];
  if (ep.positionals.length) {
    parts.push(
      `path: { ${ep.positionals.map((p) => `"${p.name}": args["${toKebab(p.name)}"] as string`).join(", ")} }`,
    );
  }
  if (queryFlags.length) {
    parts.push(
      `query: { ${queryFlags.map((q) => `"${q.raw}": ${coerce(q, helpers)}`).join(", ")} }`,
    );
  }
  if (headerFlags.length) {
    parts.push(
      `header: { ${headerFlags.map((h) => `"${h.raw}": args["${h.flag}"] as string | undefined`).join(", ")} }`,
    );
  }
  const params = `{ ${parts.join(", ")} }`;

  let run;
  if (ep.binary) {
    helpers.add("downloadCall");
    const fileParam = ep.positionals.at(-1)?.name;
    const fallback = fileParam
      ? ` || (args["${toKebab(fileParam)}"] as string)`
      : "";
    run =
      `    const output = (args.output as string | undefined)${fallback};\n` +
      `    await downloadCall(client as JoinClient, "${ep.path}", ${params}, output);\n`;
  } else if (ep.paginated) {
    helpers.add("listCall");
    helpers.add("printJson");
    run = `    printJson(await listCall(client as JoinClient, "${ep.path}", ${params}, args.all as boolean | undefined));\n`;
  } else {
    helpers.add("printJson");
    const opts = [];
    if (parts.length) opts.push(`params: ${params}`);
    if (ep.hasBody)
      opts.push(
        `body: (await readBody(args.data as string | undefined)) as never`,
      );
    run =
      `    const { data } = await (client as JoinClient).${ep.method}("${ep.path}" as never, { ${opts.join(", ")} } as never);\n` +
      `    printJson(data);\n`;
  }

  return (
    `const ${constName} = defineCommand({\n` +
    `  meta: { name: "${ep.command}", description: ${str(ep.description)} },\n` +
    `  args: {\n${args.join("\n")}\n  },\n` +
    `  async run({ args }) {\n` +
    `    const client = await resolveClient(args);\n` +
    run +
    `  },\n` +
    `});`
  );
}

function coerce(q, helpers) {
  const flag = `args["${q.flag}"]`;
  const t = q.schema.type;
  if (t === "integer" || t === "number") {
    helpers.add("numOrUndef");
    return `numOrUndef(${flag})`;
  }
  if (t === "array") {
    helpers.add("csv");
    return `csv(${flag})`;
  }
  if (t === "boolean") return `${flag} as boolean | undefined`;
  return `${flag} as string | undefined`;
}

function str(s) {
  return JSON.stringify(String(s).replace(/\s+/g, " ").trim());
}
